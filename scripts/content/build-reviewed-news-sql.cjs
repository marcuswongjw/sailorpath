// Copy-only changes to existing published rows. Drafts, publication dates and sources stay intact.
const fs = require('node:fs');
const ts = require('typescript');
const source = ts.createSourceFile('news.ts', fs.readFileSync('src/lib/news.ts', 'utf8'), ts.ScriptTarget.Latest, true);
let articles;
function visit(node) {
  if (ts.isVariableDeclaration(node) && node.name.getText(source) === 'FALLBACK_ARTICLES') {
    articles = node.initializer.elements.map(object => Object.fromEntries(object.properties.flatMap(property => {
      if (!ts.isPropertyAssignment(property)) return [];
      const value = property.initializer;
      return ts.isStringLiteralLike(value) ? [[property.name.getText(source), value.text]] : [];
    })));
  }
  ts.forEachChild(node, visit);
}
visit(source);
const wanted = new Set(['australian-2026-ilca-optimist-and-zhik-youth-sail-results','privacy-first-profiles-guardian-consent-and-evidence-protections','a-clearer-public-sailing-record','x-15-pilot-opens-ahead-of-worlds']);
const quote = value => "'" + value.replaceAll("'", "''") + "'";
const statements = articles.filter(a => wanted.has(a.slug)).map(a => `UPDATE public.news_articles SET title=${quote(a.title)}, summary=${quote(a.summary)}, body=${quote(a.body)}, updated_at=${quote(a.updatedAt)}::timestamptz\nWHERE slug=${quote(a.slug)} AND status='published' AND (title,summary,body) IS DISTINCT FROM (${quote(a.title)},${quote(a.summary)},${quote(a.body)}) RETURNING slug;`);
if (statements.length !== 4) throw new Error('Expected exactly four reviewed published articles');
fs.writeFileSync('outputs/public-copy-review-2026-11-03/reviewed-news.sql', '-- Generated by scripts/content/build-reviewed-news-sql.cjs\nBEGIN;\n'+statements.join('\n\n')+'\nCOMMIT;\n');
console.log('Prepared copy updates for four existing published articles.');
